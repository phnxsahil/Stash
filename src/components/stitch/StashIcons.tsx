import { forwardRef, type HTMLAttributes } from 'react';

type IconProps = HTMLAttributes<HTMLSpanElement> & { size?: number | string; strokeWidth?: number };
function materialIcon(name: string) {
  const Component = forwardRef<HTMLSpanElement, IconProps>(({ size, strokeWidth: _strokeWidth, className = '', style, ...props }, ref) => {
    const utilitySize = className.match(/(?:^|\s)(?:h|w|size)-(\d+(?:\.\d+)?)(?:\s|$)/)?.[1];
    return <span {...props} ref={ref} aria-hidden={props['aria-label'] ? undefined : true} className={`stash-icon ${className}`} style={{ fontSize: size || (utilitySize ? Number(utilitySize) * 4 : 24), ...style }}>{name}</span>;
  });
  Component.displayName = `StashIcon(${name})`;
  return Component;
}
